import AppKit
import XCTest
@testable import MacKVM

@MainActor
final class ClipboardSyncServiceTests: XCTestCase {
    func testStartUsesExistingClipboardAsBaselineWithoutSendingIt() {
        let store = FakeClipboardTextStore(text: "pre-existing text")
        let service = PasteboardClipboardSyncService(store: store)
        var sentTexts: [String] = []
        service.onLocalTextChange = { sentTexts.append($0) }

        service.start()
        service.poll()
        XCTAssertTrue(sentTexts.isEmpty)

        store.text = "new local text"
        service.poll()
        service.poll()

        XCTAssertEqual(sentTexts, ["new local text"])
        service.stop()
    }

    func testRemoteWriteBecomesBaselineAndDoesNotEchoBack() {
        let store = FakeClipboardTextStore(text: "old text")
        let service = PasteboardClipboardSyncService(store: store)
        var sentTexts: [String] = []
        service.onLocalTextChange = { sentTexts.append($0) }
        service.start()

        service.receive("remote text")
        service.poll()
        service.receive("remote text")

        XCTAssertEqual(store.writeAttempts, ["remote text"])
        XCTAssertTrue(sentTexts.isEmpty)
        service.stop()
    }

    func testStopAndRestartTakeAFreshBaseline() {
        let store = FakeClipboardTextStore(text: "first session text")
        let service = PasteboardClipboardSyncService(store: store)
        var sentTexts: [String] = []
        service.onLocalTextChange = { sentTexts.append($0) }

        service.start()
        service.stop()
        store.text = "changed while stopped"
        service.poll()
        XCTAssertTrue(sentTexts.isEmpty)

        service.start()
        service.poll()
        XCTAssertTrue(sentTexts.isEmpty)
        store.text = "new session text"
        service.poll()

        XCTAssertEqual(sentTexts, ["new session text"])
        service.stop()
    }

    func testFailedRemoteWriteCanBeRetriedWithoutChangingTheBaseline() {
        let store = FakeClipboardTextStore(text: "local text")
        let service = PasteboardClipboardSyncService(store: store)
        var sentTexts: [String] = []
        service.onLocalTextChange = { sentTexts.append($0) }
        service.start()

        store.writeSucceeds = false
        service.receive("remote text")
        store.writeSucceeds = true
        service.receive("remote text")
        service.poll()

        XCTAssertEqual(store.writeAttempts, ["remote text", "remote text"])
        XCTAssertEqual(store.text, "remote text")
        XCTAssertTrue(sentTexts.isEmpty)
        service.stop()
    }

    func testPasteboardMarkerPolicyRejectsSensitiveTypes() {
        let markedTypes = [
            NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
            NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
            NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
        ]

        for marker in markedTypes {
            XCTAssertFalse(
                ClipboardPasteboardMarkerPolicy.permits([.string, marker])
            )
        }

        XCTAssertFalse(ClipboardPasteboardMarkerPolicy.permits(markedTypes))
        XCTAssertTrue(
            ClipboardPasteboardMarkerPolicy.permits([
                NSPasteboard.PasteboardType("public.utf8-plain-text")
            ])
        )
    }
}

private final class FakeClipboardTextStore: ClipboardTextStore {
    var text: String?
    var writeSucceeds = true
    private(set) var writeAttempts: [String] = []

    init(text: String?) {
        self.text = text
    }

    func readPermittedPlainText() -> String? {
        text
    }

    func writePlainText(_ text: String) -> Bool {
        writeAttempts.append(text)
        guard writeSucceeds else { return false }
        self.text = text
        return true
    }
}
