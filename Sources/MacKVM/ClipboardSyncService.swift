import AppKit
import Foundation
import MacKVMCore

protocol ClipboardTextStore: AnyObject {
    func readPermittedPlainText() -> String?
    func writePlainText(_ text: String) -> Bool
}

protocol ClipboardSyncManaging: AnyObject {
    var onLocalTextChange: ((String) -> Void)? { get set }
    func start()
    func receive(_ text: String)
    func stop()
}

/// Polls only while an opted-in control session is active. Starting a session
/// snapshots the existing clipboard as a baseline; it never sends that stale
/// value merely because control was granted.
final class PasteboardClipboardSyncService: ClipboardSyncManaging {
    private static let pollingInterval: TimeInterval = 0.4

    var onLocalTextChange: ((String) -> Void)?

    private let store: any ClipboardTextStore
    private var timer: Timer?
    private var lastObservedText: String?
    private var isRunning = false

    init() {
        store = GeneralPasteboardTextStore()
    }

    init(store: any ClipboardTextStore) {
        self.store = store
    }

    func start() {
        dispatchPrecondition(condition: .onQueue(.main))
        stop()
        isRunning = true
        lastObservedText = store.readPermittedPlainText()
        let timer = Timer(
            timeInterval: Self.pollingInterval,
            repeats: true
        ) { [weak self] _ in
            self?.poll()
        }
        self.timer = timer
        RunLoop.main.add(timer, forMode: .common)
    }

    func receive(_ text: String) {
        dispatchPrecondition(condition: .onQueue(.main))
        guard isRunning,
              text.utf8.count <= ControlMessageCodec.maximumClipboardUTF8Length else {
            return
        }
        guard store.readPermittedPlainText() != text else {
            lastObservedText = text
            return
        }
        guard store.writePlainText(text) else { return }
        // Treat the remote write as the new baseline so it cannot echo back
        // on the next poll.
        lastObservedText = text
    }

    func stop() {
        dispatchPrecondition(condition: .onQueue(.main))
        timer?.invalidate()
        timer = nil
        isRunning = false
        lastObservedText = nil
    }

    /// Kept internal so lifecycle and echo behavior can be exercised
    /// deterministically without waiting on a desktop timer in tests.
    func poll() {
        guard isRunning else { return }
        let text = store.readPermittedPlainText()
        guard text != lastObservedText else { return }
        lastObservedText = text
        guard let text,
              text.utf8.count <= ControlMessageCodec.maximumClipboardUTF8Length else {
            return
        }
        onLocalTextChange?(text)
    }
}

enum ClipboardPasteboardMarkerPolicy {
    private static let excludedTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    ]

    static func permits(_ types: [NSPasteboard.PasteboardType]) -> Bool {
        excludedTypes.isDisjoint(with: types)
    }
}

private final class GeneralPasteboardTextStore: ClipboardTextStore {
    private let pasteboard = NSPasteboard.general

    func readPermittedPlainText() -> String? {
        guard ClipboardPasteboardMarkerPolicy.permits(pasteboard.types ?? []) else {
            return nil
        }
        return pasteboard.string(
            forType: NSPasteboard.PasteboardType("public.utf8-plain-text")
        )
    }

    func writePlainText(_ text: String) -> Bool {
        guard ClipboardPasteboardMarkerPolicy.permits(pasteboard.types ?? []) else {
            return false
        }
        pasteboard.clearContents()
        return pasteboard.setString(
            text,
            forType: NSPasteboard.PasteboardType("public.utf8-plain-text")
        )
    }
}
